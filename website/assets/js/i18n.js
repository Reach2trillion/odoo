/* Current language: ?lang= wins, then localStorage, then browser, then English. */
function detectLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && I18N[q]) return q;
  const saved = localStorage.getItem('abj_lang');
  if (saved && I18N[saved]) return saved;
  return (navigator.language || '').toLowerCase().startsWith('km') ? 'km' : 'en';
}

let LANG = detectLang();

const t = (key) => (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
const tv = (obj) => (obj ? obj[LANG] || obj.en : '');

function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  localStorage.setItem('abj_lang', lang);
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(',').forEach((pair) => {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
  document.querySelectorAll('.lang-switch button').forEach((b) => {
    b.classList.toggle('is-active', b.dataset.lang === LANG);
  });
}
